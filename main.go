// ФОНОВАЯ ПРОВЕРКА ХОСТОВ
// ============================================================================

// checkHost — фоновая горутина, которая проверяет доступность одного хоста
// Запускается один раз для каждого хоста и работает до закрытия программы
func (a *App) checkHost(id int) {
	// Создаём тикер (таймер), который срабатывает каждые 3 секунды
	ticker := time.NewTicker(3 * time.Second)
	defer ticker.Stop() // Освобождаем ресурсы при завершении

	for {
		select {
		case <-a.ctx.Done():
			// Если приложение закрывается (контекст отменён) — выходим из цикла
			return
		case <-ticker.C:
			// Каждые 3 секунды выполняем проверку
			
			// === ЧТЕНИЕ АДРЕСА ===
			a.mu.Lock()
			var addr string
			for _, h := range a.hosts {
				if h.ID == id {
					addr = h.Addr
					break
				}
			}
			a.mu.Unlock()

			// Если адрес пустой (хост удалили) — прекращаем проверку
			if addr == "" {
				return
			}
			
			// Если порт не указан, добавляем :80 (HTTP)
			if !strings.Contains(addr, ":") {
				addr += ":80"
			}

			// === ПРОВЕРКА ДОСТУПНОСТИ ===
			// Запоминаем время начала
			start := time.Now()
			
			// Пытаемся установить TCP-соединение с таймаутом 2 секунды
			conn, err := net.DialTimeout("tcp", addr, 2*time.Second)
			
			// Вычисляем прошедшее время
			elapsed := time.Since(start)
			
			// Если соединение успешно — закрываем его
			if err == nil {
				conn.Close()
			}

			// === ОБНОВЛЕНИЕ СТАТУСА ===
			a.mu.Lock()
			for i := range a.hosts {
				if a.hosts[i].ID == id {
					if err == nil {
						// Хост доступен — зелёный статус + время в мс
						a.hosts[i].Status = "ok"
						a.hosts[i].Latency = fmt.Sprintf("%d мс", elapsed.Milliseconds())
					} else {
						// Хост недоступен — красный статус, пустое время
						a.hosts[i].Status = "error"
						a.hosts[i].Latency = ""
					}
					break
				}
			}
			a.mu.Unlock()
			// JavaScript сам опрашивает GetHosts() каждые 2 секунды
			// и обновляет интерфейс
		}
	}
}

