// NewApp создаёт и возвращает новый экземпляр приложения
// Вызывается один раз при запуске программы
func NewApp() *App {
	return &App{
		hosts:  make([]HostEntry, 0), // Создаём пустой слайс (массив) для хостов
		nextID: 1,                     // Первый хост получит ID = 1
	}
}

// ============================================================================
// ЖИЗНЕННЫЙ ЦИКЛ ПРИЛОЖЕНИЯ
