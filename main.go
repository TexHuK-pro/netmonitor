// AddHost добавляет новый хост в список
// Возвращает ID добавленного хоста
// Вызывается из JavaScript при нажатии кнопки "Добавить"
func (a *App) AddHost(name, addr string) int {
	// Блокируем мьютекс для безопасной записи
	a.mu.Lock()
	
	id := a.nextID
	a.nextID++
	
	// Создаём новую запись
	entry := HostEntry{
		ID:     id,
		Name:   name,
		Addr:   addr,
		Status: "checking", // Пока идёт проверка, показываем серый индикатор
	}
	
	// Добавляем в список
	a.hosts = append(a.hosts, entry)
	a.mu.Unlock() // Разблокируем

	// Запускаем фоновую проверку этого хоста
	// go — ключевое слово для запуска в отдельной горутине (потоке)
	go a.checkHost(id)
	
	// Сохраняем обновлённый список в файл
	a.SaveConfig()
	
	return id // Возвращаем ID (JavaScript может его использовать)
}

// RemoveHost удаляет хост по ID
// Вызывается из JavaScript при нажатии кнопки "Удалить"
func (a *App) RemoveHost(id int) {
	a.mu.Lock()
	
	// Ищем хост с нужным ID
	for i, h := range a.hosts {
		if h.ID == id {
			// Удаляем элемент из слайса:
			// a.hosts[:i] — всё до удаляемого
			// a.hosts[i+1:] — всё после удаляемого
			a.hosts = append(a.hosts[:i], a.hosts[i+1:]...)
			break
		}
	}
	
	a.mu.Unlock()
	
	// Сохраняем обновлённый список в файл
	a.SaveConfig()
}

// GetHosts возвращает текущий список всех хостов
// Вызывается из JavaScript каждые 2 секунды для обновления интерфейса
func (a *App) GetHosts() []HostEntry {
	a.mu.Lock()
	defer a.mu.Unlock() // Автоматическая разблокировка при выходе из функции
	return a.hosts
}

