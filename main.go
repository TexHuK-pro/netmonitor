// App — главная структура приложения (экземпляр создаётся один при запуске)
// Все методы этой структуры автоматически становятся доступны из JavaScript
type App struct {
	ctx    context.Context // Контекст приложения (нужен для остановки горутин при закрытии)
	hosts  []HostEntry     // Список всех добавленных хостов (хранится в памяти)
	mu     sync.Mutex      // Мьютекс для защиты списка hosts от одновременного доступа
	nextID int             // Счётчик для генерации уникальных ID новым хостам
}

// HostEntry — структура одного хоста (адреса для проверки)
// Теги `json:"..."` нужны для автоматической конвертации в JSON
// Это позволяет передавать данные между Go и JavaScript
type HostEntry struct {
	ID      int    `json:"id"`      // Уникальный номер хоста (1, 2, 3...)
	Name    string `json:"name"`    // Название (например, "Google DNS")
	Addr    string `json:"addr"`    // Адрес (например, "8.8.8.8:53")
	Status  string `json:"status"`  // Статус: "ok" (зелёный), "error" (красный), "checking" (серый)
	Latency string `json:"latency"` // Время отклика в мс (например, "45 мс")
}

// ConfigEntry — упрощённая структура для сохранения в файл
// Не содержит статус и задержку (они вычисляются при запуске)
type ConfigEntry struct {
	Name string `json:"name"` // Название хоста
	Addr string `json:"addr"` // Адрес хоста
}

