// main — главная функция, с которой начинается выполнение программы
func main() {
	// Создаём экземпляр приложения
	app := NewApp()

	// Запускаем Wails с настройками
	err := wails.Run(&options.App{
		Title:     "🌐 Network Monitor",      // Заголовок окна
		Width:     900,                       // Ширина окна в пикселях
		Height:    600,                       // Высота окна в пикселях
		OnStartup: app.Startup,               // Функция, которая вызывается при запуске
		
		// Настройка сервера статических файлов (фронтенд)
		AssetServer: &assetserver.Options{
			Assets: assets, // Встроенные файлы из frontend/dist
		},
		
		// Привязка Go-объектов к JavaScript
		// После этого методы app.* становятся доступны как window.go.main.App.*
		Bind: []interface{}{app},
	})

	// Если произошла ошибка — выводим в консоль
	if err != nil {
		println("Error:", err.Error())
	}
}