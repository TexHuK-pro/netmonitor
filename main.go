// Startup вызывается сразу после создания окна приложения
// Здесь мы загружаем сохранённые адреса из файла
func (a *App) Startup(ctx context.Context) {
	a.ctx = ctx       // Сохраняем контекст (нужен для остановки проверок)
	a.LoadConfig()    // Загружаем список хостов из config.json
}

