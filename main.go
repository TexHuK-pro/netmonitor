// LoadConfig читает файл config.json и восстанавливает список хостов
// Вызывается один раз при запуске программы
func (a *App) LoadConfig() {
	// Пытаемся прочитать файл
	data, err := os.ReadFile(configFile)
	if err != nil {
		// Если файла нет — это нормально (первый запуск)
		if os.IsNotExist(err) {
			return
		}
		// Если другая ошибка — выводим в консоль
		println("Ошибка загрузки конфига:", err.Error())
		return
	}

	// Парсим JSON в слайс структур ConfigEntry
	var entries []ConfigEntry
	if err := json.Unmarshal(data, &entries); err != nil {
		println("Ошибка парсинга конфига:", err.Error())
		return
	}

	// Блокируем мьютекс (защита от одновременного доступа из разных горутин)
	a.mu.Lock()
	
	// Очищаем текущий список и создаём новый нужного размера
	a.hosts = make([]HostEntry, 0, len(entries))
	a.nextID = 1
	
	// Для каждого сохранённого хоста создаём полноценный HostEntry
	for _, e := range entries {
		id := a.nextID
		a.nextID++
		
		a.hosts = append(a.hosts, HostEntry{
			ID:     id,           // Уникальный ID
			Name:   e.Name,       // Название из файла
			Addr:   e.Addr,       // Адрес из файла
			Status: "checking",   // При запуске считаем, что идёт проверка
		})
	}
	
	a.mu.Unlock() // Разблокируем мьютекс

	// Запускаем фоновые проверки для всех загруженных хостов
	for _, h := range a.hosts {
		go a.checkHost(h.ID) // Каждая проверка работает в отдельной горутине
	}
}

// SaveConfig записывает текущий список хостов в файл config.json
// Вызывается после каждого добавления или удаления хоста
func (a *App) SaveConfig() {
	// Блокируем мьютекс для безопасного чтения списка
	a.mu.Lock()
	
	// Создаём упрощённый список только с Name и Addr
	entries := make([]ConfigEntry, len(a.hosts))
	for i, h := range a.hosts {
		entries[i] = ConfigEntry{
			Name: h.Name,
			Addr: h.Addr,
		}
	}
	
	a.mu.Unlock() // Разблокируем

	// Конвертируем в JSON с отступами (для читаемости файла)
	data, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		println("Ошибка сохранения конфига:", err.Error())
		return
	}

	// Записываем в файл с правами 0644 (чтение/запись для владельца, чтение для остальных)
	if err := os.WriteFile(configFile, data, 0644); err != nil {
		println("Ошибка записи файла:", err.Error())
	}
}

